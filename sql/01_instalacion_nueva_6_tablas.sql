-- ESQUEMA DE REFERENCIA COMPLETO / INSTALACION NUEVA SOLAMENTE.
-- Si ya tiene CITA_MEDICA con las 6 tablas y CODIGO_MEDICO, NO ejecutar.
CREATE DATABASE IF NOT EXISTS CITA_MEDICA CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE CITA_MEDICA;
CREATE TABLE IF NOT EXISTS ESPECIALIDAD (
 CODIGO_ESPECIALIDAD CHAR(8) NOT NULL PRIMARY KEY,
 NOMBRE_ESPECIALIDAD VARCHAR(80) NOT NULL UNIQUE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS PACIENTE (
 CODIGO_PAC CHAR(6) NOT NULL PRIMARY KEY,
 NOMBRE_PAC VARCHAR(100) NOT NULL,
 EDAD_PAC INT NOT NULL,
 TELEFONO_PAC CHAR(9) NULL,
 CONSTRAINT CK_EDAD_PAC CHECK (EDAD_PAC BETWEEN 0 AND 120)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS MEDICO (
 CODIGO_MEDICO CHAR(6) NOT NULL PRIMARY KEY,
 NOMBRE_MEDICO VARCHAR(120) NOT NULL,
 CODIGO_ESPECIALIDAD CHAR(8) NOT NULL,
 CONSTRAINT FK_MEDICO_ESPECIALIDAD FOREIGN KEY (CODIGO_ESPECIALIDAD)
  REFERENCES ESPECIALIDAD(CODIGO_ESPECIALIDAD)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS SERVICIO (
 CODIGO_SERV CHAR(8) NOT NULL PRIMARY KEY,
 NOMBRE_SERV VARCHAR(120) NOT NULL,
 PRECIO_SERV DECIMAL(10,2) NOT NULL,
 CODIGO_ESPECIALIDAD CHAR(8) NOT NULL,
 CONSTRAINT FK_SERVICIO_ESPECIALIDAD FOREIGN KEY (CODIGO_ESPECIALIDAD)
  REFERENCES ESPECIALIDAD(CODIGO_ESPECIALIDAD),
 CONSTRAINT CK_PRECIO_SERV CHECK (PRECIO_SERV >= 0)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS CITA (
 CODIGO_CIT CHAR(8) NOT NULL PRIMARY KEY,
 FECHA_CIT DATE NOT NULL,
 HORA_CIT TIME NOT NULL,
 CODIGO_PAC CHAR(6) NOT NULL,
 CONSTRAINT FK_CITA_PACIENTE FOREIGN KEY(CODIGO_PAC) REFERENCES PACIENTE(CODIGO_PAC)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS DETALLE_CITA (
 CODIGO_CIT CHAR(8) NOT NULL,
 CODIGO_SERV CHAR(8) NOT NULL,
 CANTIDAD INT NOT NULL DEFAULT 1,
 HORA_SERV TIME NULL,
 FECHA_SERVICIO DATE NULL,
 CODIGO_MEDICO CHAR(6) NULL,
 CONSTRAINT PK_DETALLE_CITA PRIMARY KEY (CODIGO_CIT, CODIGO_SERV),
 CONSTRAINT FK_DETALLE_CITA_CITA FOREIGN KEY(CODIGO_CIT) REFERENCES CITA(CODIGO_CIT) ON DELETE CASCADE,
 CONSTRAINT FK_DETALLE_CITA_SERV FOREIGN KEY(CODIGO_SERV) REFERENCES SERVICIO(CODIGO_SERV),
 CONSTRAINT FK_DETALLE_CITA_MEDICO FOREIGN KEY(CODIGO_MEDICO) REFERENCES MEDICO(CODIGO_MEDICO),
 CONSTRAINT CK_CANTIDAD CHECK (CANTIDAD > 0)
) ENGINE=InnoDB;
-- Nota: CREATE TABLE IF NOT EXISTS NO corrige tablas existentes; usar esquema_verificacion.sql.
