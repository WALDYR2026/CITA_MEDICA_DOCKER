-- Ejecutar en la MISMA conexión (host/3307/esquema) que usa Spring Boot.
SELECT @@hostname AS HOST, @@port AS PUERTO, DATABASE() AS BD_ACTUAL;
SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, IS_NULLABLE
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA='CITA_MEDICA'
ORDER BY TABLE_NAME, ORDINAL_POSITION;
SHOW CREATE TABLE CITA_MEDICA.DETALLE_CITA;
SELECT d.CODIGO_CIT, p.NOMBRE_PAC, s.NOMBRE_SERV, e.NOMBRE_ESPECIALIDAD,
 m.NOMBRE_MEDICO, d.CANTIDAD, d.FECHA_SERVICIO, d.HORA_SERV
FROM CITA_MEDICA.DETALLE_CITA d
JOIN CITA_MEDICA.CITA c ON c.CODIGO_CIT=d.CODIGO_CIT
JOIN CITA_MEDICA.PACIENTE p ON p.CODIGO_PAC=c.CODIGO_PAC
JOIN CITA_MEDICA.SERVICIO s ON s.CODIGO_SERV=d.CODIGO_SERV
JOIN CITA_MEDICA.ESPECIALIDAD e ON e.CODIGO_ESPECIALIDAD=s.CODIGO_ESPECIALIDAD
LEFT JOIN CITA_MEDICA.MEDICO m ON m.CODIGO_MEDICO=d.CODIGO_MEDICO
ORDER BY d.CODIGO_CIT, d.FECHA_SERVICIO, d.HORA_SERV;
